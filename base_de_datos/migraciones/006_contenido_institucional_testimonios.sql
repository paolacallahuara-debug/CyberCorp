-- 8) Completa los nuevos números con el WhatsApp general cuando estén vacíos.
UPDATE public.configuracion_empresa
SET
  whatsapp_cursos = COALESCE(NULLIF(whatsapp_cursos, ''), whatsapp),
  whatsapp_servicios = COALESCE(NULLIF(whatsapp_servicios, ''), whatsapp)
WHERE whatsapp_cursos IS NULL OR whatsapp_servicios IS NULL;
