-- Evita rangos de fechas invertidos. Los bloques comprueban si la
-- restricción ya existe antes de crearla.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'cursos_fechas_validas'
      AND conrelid = 'public.cursos'::regclass
  ) THEN
    ALTER TABLE public.cursos
      ADD CONSTRAINT cursos_fechas_validas
      CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio);
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'kits_fechas_validas'
      AND conrelid = 'public.kits'::regclass
  ) THEN
    ALTER TABLE public.kits
      ADD CONSTRAINT kits_fechas_validas
      CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin >= fecha_inicio);
  END IF;
END $$;

-- 2) CONVENIOS
CREATE TABLE IF NOT EXISTS public.convenios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  descripcion TEXT,
  imagen_url TEXT,
  enlace_url TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_convenios_activo ON public.convenios(activo);

-- 3) TESTIMONIOS
CREATE TABLE IF NOT EXISTS public.testimonios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  nombre_cliente TEXT,
  descripcion TEXT,
  tipo_video TEXT NOT NULL DEFAULT 'url'
    CHECK (tipo_video IN ('archivo', 'url')),
  video_url TEXT,
  video_externo_url TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (tipo_video = 'archivo' AND video_url IS NOT NULL)
    OR
    (tipo_video = 'url' AND video_externo_url IS NOT NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_testimonios_activo ON public.testimonios(activo);

-- 4) PUBLICACIONES DE TIKTOK
CREATE TABLE IF NOT EXISTS public.tiktok_publicaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT,
  tiktok_url TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tiktok_publicaciones_activo
  ON public.tiktok_publicaciones(activo);

-- Si alguna de estas tablas fue creada manualmente con un BIGINT simple,
-- aseguramos que el id también pueda generarse automáticamente desde el panel.
DO $$
DECLARE siguiente BIGINT;
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'convenios' AND column_name = 'id'
      AND is_identity = 'NO' AND column_default IS NULL
  ) THEN
    CREATE SEQUENCE IF NOT EXISTS public.convenios_id_seq;
    SELECT COALESCE(MAX(id), 0) + 1 INTO siguiente FROM public.convenios;
    PERFORM setval('public.convenios_id_seq', siguiente, false);
    ALTER TABLE public.convenios ALTER COLUMN id SET DEFAULT nextval('public.convenios_id_seq');
    ALTER SEQUENCE public.convenios_id_seq OWNED BY public.convenios.id;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'testimonios' AND column_name = 'id'
      AND is_identity = 'NO' AND column_default IS NULL
  ) THEN
    CREATE SEQUENCE IF NOT EXISTS public.testimonios_id_seq;
    SELECT COALESCE(MAX(id), 0) + 1 INTO siguiente FROM public.testimonios;
    PERFORM setval('public.testimonios_id_seq', siguiente, false);
    ALTER TABLE public.testimonios ALTER COLUMN id SET DEFAULT nextval('public.testimonios_id_seq');
    ALTER SEQUENCE public.testimonios_id_seq OWNED BY public.testimonios.id;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'tiktok_publicaciones' AND column_name = 'id'
      AND is_identity = 'NO' AND column_default IS NULL
  ) THEN
    CREATE SEQUENCE IF NOT EXISTS public.tiktok_publicaciones_id_seq;
    SELECT COALESCE(MAX(id), 0) + 1 INTO siguiente FROM public.tiktok_publicaciones;
    PERFORM setval('public.tiktok_publicaciones_id_seq', siguiente, false);
    ALTER TABLE public.tiktok_publicaciones ALTER COLUMN id SET DEFAULT nextval('public.tiktok_publicaciones_id_seq');
    ALTER SEQUENCE public.tiktok_publicaciones_id_seq OWNED BY public.tiktok_publicaciones.id;
  END IF;
END $$;

